"""SSLv2 Protocol Version
============================

.. module:: pcapkit.const.sslv2.version

This module contains the constant enumeration for **SSLv2 Protocol
Version**, hand-curated rather than generated by a
:class:`~pcapkit.vendor.default.Vendor` crawler, for the same reason
:class:`pcapkit.const.sslv2.handshake_type.HandshakeType` is: the value below
comes from the expired Netscape SSLv2 draft [*]_, not a live registry.

SSLv2 carries no record-layer version field; ``CLIENT-VERSION`` and
``SERVER-VERSION`` are handshake-body fields. See :meth:`Version._missing_`
for values other than ``SSLv2``.

.. [*] https://datatracker.ietf.org/doc/html/draft-hickman-netscape-ssl-00

"""

from typing import TYPE_CHECKING

from aenum import IntEnum

from pcapkit.corekit.enum import EnumRegistry
from pcapkit.utilities.exceptions import EnumValueError

if TYPE_CHECKING:
    from typing import Any

__all__ = ['Version']


class Version(EnumRegistry, IntEnum):
    """[Version] SSLv2 Protocol Version"""

    #: ``SSL-2.0``
    SSLv2 = 0x0002

    @classmethod
    def _validate_value(cls, value: 'Any') -> 'None':
        """Reject ``value`` unless it passes the range check :meth:`_missing_` makes.

        Overrides :meth:`~pcapkit.corekit.enum.EnumLookup._validate_value`
        with that check and the message it raises, so
        :meth:`~pcapkit.corekit.enum.EnumRegistry.register` refuses exactly the
        values :meth:`~pcapkit.corekit.enum.EnumLookup.get` refuses, in the
        same words (:issue:`1816`).

        Args:
            value: Value about to be looked up or minted.

        Raises:
            EnumValueError: If ``value`` fails that check. A
                :exc:`ValueError`, so an ``except ValueError`` caller is
                unaffected.

        """
        if not (isinstance(value, int) and 0x0000 <= value <= 0xFFFF):
            raise EnumValueError('%r is not a valid %s' % (value, cls.__name__))

    @classmethod
    def _missing_(cls, value: 'int') -> 'Version':
        """Lookup function used when value is not found.

        A ``CLIENT-VERSION``/``SERVER-VERSION`` other than ``0x0002`` is not
        necessarily malformed: per :rfc:`6101#appendix-E`, an SSLv3-capable
        client sends an SSLv2-framed ``CLIENT-HELLO`` whose version reads
        ``768`` (``0x0300``). So any unrecognised value resolves to an
        unregistered member rather than raising.

        Args:
            value: Value to get enum item.

        """
        if not (isinstance(value, int) and 0x0000 <= value <= 0xFFFF):
            raise ValueError('%r is not a valid %s' % (value, cls.__name__))
        return cls._unregistered_member(value, 'Unassigned')
