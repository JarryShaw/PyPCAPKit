# -*- coding: utf-8 -*-
"""Unit tests for :mod:`pcapkit.const.sslv2.handshake_type` and
:mod:`pcapkit.const.sslv2.version` (:issue:`2457`).

Both registries are generated by a :class:`~pcapkit.vendor.default.Vendor`
crawler (:mod:`pcapkit.vendor.sslv2`) that reads a ``DATA`` attribute instead
of fetching a URL, since their source -- the expired SSLv2 draft -- is not a
live registry a crawler could re-fetch. They still follow this package's
lookup contract: a registered member resolves by value, an unregistered one
resolves to a nameless ``Unassigned`` member without being minted into the
registry (:issue:`860`), and a value outside the member type's own range
raises.

"""
from __future__ import annotations

import unittest

#: Test tier (#1958): pure-Python lookups over a closed registry, which
#: behave the same on every interpreter.
__tier__ = 'LATEST'


class HandshakeTypeTests(unittest.TestCase):
    """:class:`pcapkit.const.sslv2.handshake_type.HandshakeType`."""

    def test_every_draft_code_resolves_by_name_and_value(self) -> None:
        from pcapkit.const.sslv2.handshake_type import HandshakeType

        expected = {
            'ERROR': 0, 'CLIENT_HELLO': 1, 'CLIENT_MASTER_KEY': 2, 'CLIENT_FINISHED': 3,
            'SERVER_HELLO': 4, 'SERVER_VERIFY': 5, 'SERVER_FINISHED': 6,
            'REQUEST_CERTIFICATE': 7, 'CLIENT_CERTIFICATE': 8,
        }
        for name, value in expected.items():
            with self.subTest(name=name):
                member = HandshakeType[name]
                self.assertEqual(member.value, value)
                self.assertEqual(HandshakeType(value), member)

    def test_unknown_code_resolves_to_an_unregistered_member(self) -> None:
        from pcapkit.const.sslv2.handshake_type import HandshakeType

        before = len(HandshakeType.__members__)  # type: ignore[attr-defined]
        member = HandshakeType(50)
        self.assertEqual(member.value, 50)
        self.assertEqual(member.name, 'Unassigned')
        # #860: a miss never mints a new registered member.
        self.assertEqual(len(HandshakeType.__members__), before)  # type: ignore[attr-defined]

    def test_out_of_range_value_raises(self) -> None:
        from pcapkit.const.sslv2.handshake_type import HandshakeType

        for bad in (-1, 256, 'ERROR'):
            with self.subTest(value=bad):
                with self.assertRaises(ValueError):
                    HandshakeType(bad)


class VersionTests(unittest.TestCase):
    """:class:`pcapkit.const.sslv2.version.Version`."""

    def test_sslv2_resolves(self) -> None:
        from pcapkit.const.sslv2.version import Version

        self.assertEqual(Version(0x0002), Version.SSLv2)
        self.assertEqual(Version['SSLv2'].value, 0x0002)

    def test_unknown_version_resolves_to_an_unregistered_member(self) -> None:
        from pcapkit.const.sslv2.version import Version

        before = len(Version.__members__)  # type: ignore[attr-defined]
        member = Version(0x0300)
        self.assertEqual(member.value, 0x0300)
        self.assertEqual(member.name, 'Unassigned')
        self.assertEqual(len(Version.__members__), before)  # type: ignore[attr-defined]

    def test_out_of_range_value_raises(self) -> None:
        from pcapkit.const.sslv2.version import Version

        for bad in (-1, 0x10000, 'SSLv2'):
            with self.subTest(value=bad):
                with self.assertRaises(ValueError):
                    Version(bad)


if __name__ == '__main__':
    unittest.main()
