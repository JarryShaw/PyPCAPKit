# -*- coding: utf-8 -*-
"""The deferred-pickle fix of :issue:`2417`, end to end over the real captures.

:mod:`tests.foundation.reassembly.test_datagram_deferred_pickle_2417_unit`
synthesises a single TCP datagram directly, on an unassigned and an assigned
flow. This reassembles every TCP flow out of :data:`CAPTURES` instead, with
each datagram's ``packet`` left deferred, and pins the same round trip -- which
is how the bug was originally found: a datagram is only worth pickling *while*
its payload is unresolved, so the failure sat exactly where nothing else would
catch it.

The module reads generated captures, so it belongs to the fixture-dependent
tier.

"""
from __future__ import annotations

import pickle
import unittest
from typing import TYPE_CHECKING

from tests._tiers import SAMPLE_ROOT

if TYPE_CHECKING:
    from typing import Any

#: Test tier (#1958): exercises pickling, whose protocols differ by interpreter.
__tier__ = 'ALL'

#: The sample captures carrying TCP flows, i.e. the ones reassembly has anything
#: to do. Generated by ``examples/generators/make_samples.py``.
CAPTURES = ('http.pcap', 'stream.pcap', 'tcp.pcap', 'http6.cap')


def _held(datagram: 'Any') -> 'Any':
    """``datagram``'s unresolved ``packet`` placeholder, without resolving it."""
    key = datagram.__map__.get('packet', 'packet')
    return datagram.__dict__[key]


class SampleCaptureDatagramPickleTests(unittest.TestCase):
    """The same thing over the real captures, which is how the bug was found."""

    @staticmethod
    def _deferred_datagrams(path: 'Any') -> 'list[Any]':
        """Every TCP datagram ``path`` reassembles, packets left unresolved."""
        import pcapkit

        extraction = pcapkit.extract(fin=str(path), nofile=True, store=True,
                                     tcp=True, reassembly=True)
        return [datagram for datagram in extraction.reassembly.tcp
                if _held(datagram) is not None]

    def test_every_capture_with_tcp_flows_round_trips(self) -> None:
        """Each of the named samples, every datagram, packets still deferred."""
        for name in CAPTURES:
            path = SAMPLE_ROOT / name
            with self.subTest(capture=name):
                self.assertTrue(path.is_file(),
                                f'{path} is missing; run examples/generators/make_samples.py')

                datagrams = self._deferred_datagrams(path)
                self.assertNotEqual(datagrams, [],
                                    f'{name} reassembled no deferred TCP datagram, '
                                    'so it pins nothing')

                for index, datagram in enumerate(datagrams):
                    restored = pickle.loads(pickle.dumps(datagram))

                    self.assertEqual(_held(restored).proto, _held(datagram).proto,
                                     f'{name} datagram {index} lost its ports')
                    self.assertEqual(bytes(restored.payload), bytes(datagram.payload))


if __name__ == '__main__':
    unittest.main()
